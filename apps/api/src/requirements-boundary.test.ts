import { test } from 'node:test';
import assert from 'node:assert/strict';
import Fastify from 'fastify';
import type { Pool } from 'pg';
import type { ProjectStore } from './project-store.js';
import type { DocumentStore } from './documents/store.js';
import { registerAgentRoutes } from './agent/routes.js';
import { registerPracticeRoutes } from './practice/routes.js';
import { registerDocumentRoutes } from './documents/routes.js';
const project='11111111-1111-4111-8111-111111111111', requirement='22222222-2222-4222-8222-222222222222';
const auth={authorization:`Bearer ${'a'.repeat(64)}`};
const ai={baseUrl:'https://example.test',apiKey:'test-only-placeholder',model:'fixture',timeoutMs:1000};
for(const kind of ['agent','tests','documents'] as const) test(`${kind} blocks an oversized requirement before any model request or write`,async t=>{
 let models=0,writes=0;
 const content='需求'.repeat(24980)+'末尾关键条件：审批必须由两人共同完成。';
 const store={userBySession:async()=>({id:project}),getProject:async()=>({id:project}),listRequirements:async()=>[{id:requirement,version:1,status:'confirmed',content}]} as unknown as ProjectStore;
 const pool={query:async()=>{writes++;return{rows:[{id:project}]};}} as unknown as Pool;
 const documents={getContext:async()=>{writes++;return{tasks:[],testCases:[],testCounts:{total:0}};},create:async()=>{writes++;return{};}} as unknown as DocumentStore;
 const complete=async()=>{models++;return '{}';};
 const app=Fastify();t.after(()=>app.close());
 if(kind==='agent')await registerAgentRoutes(app,store,pool,ai,undefined,{complete});
 if(kind==='tests')await registerPracticeRoutes(app,store,pool,ai,{complete});
 if(kind==='documents')await registerDocumentRoutes(app,store,documents,ai,complete);
 const suffix=kind==='agent'?'agent/runs':kind==='tests'?'test-cases':'documents/generate';
 const result=await app.inject({method:'POST',url:`/projects/${project}/${suffix}`,headers:auth,payload:kind==='documents'?{type:'readme'}:{requirementId:requirement}});
 assert.equal(result.statusCode,413);assert.equal(result.json().error,'requirement_generation_limit');
 assert.equal(result.json().actual,content.length);assert.equal(models,0);assert.equal(writes,0);
});
